//! The models.dev catalog: where a model's context window comes from (ADR 0018 §目录).
//!
//! The window is **not** guessed from the model name. It is either the host's explicit
//! `--context-window`, a lookup in the public models.dev catalog matched by
//! `(provider, model)`, or — for a provider models.dev does not carry (`chatgpt`) — the numbers
//! the route's own descriptor table cites ([`crate::DescriptorModel::limit`], read from
//! `@oh-my-pi/pi-catalog`'s `openai-codex` block). The catalog is fetched over a read-only GET
//! with no key, no header and no user data, cached owner-only under the same cache root as the
//! diagnostics (ADR 0013 decision 4), and refreshed at most once every [`CACHE_TTL`].
//!
//! The fetch is deliberately allowed to fail: a missing or stale catalog leaves the window
//! unknown and the guard off (ADR 0015), never a guessed number.

use std::collections::BTreeMap;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::sync::OnceLock;
use std::time::{Duration, SystemTime};

use serde_json::Value;

/// The public catalog. Overridable with `RADIAN_CATALOG_URL` (a test seam; not in `--help`).
pub const CATALOG_URL: &str = "https://models.dev/api.json";
/// Re-fetch at most this often; inside it, the cache is used without any network call.
pub const CACHE_TTL: Duration = Duration::from_secs(24 * 60 * 60);
/// The whole fetch is bounded by this; a slow catalog must not hold up startup.
pub const FETCH_TIMEOUT: Duration = Duration::from_secs(3);

/// The trimmed models.dev snapshot compiled into the binary (ADR 0026):
/// the last level of [`load`], so a first run with no cache and no network still has windows,
/// prices and wire protocols. Regenerated by
/// `crates/radian-host/scripts/update-catalog-snapshot.py`; never fetched at run time.
pub const CATALOG_SNAPSHOT: &str = include_str!("catalog-snapshot.json");

/// The date the bundled snapshot was fetched (its `_date`; a unit test keeps the two in sync).
pub const SNAPSHOT_DATE: &str = "2026-10-17";

/// The bundled snapshot, parsed once. The parse is an `expect`: a corrupt snapshot is a
/// build/test failure (`the_bundled_snapshot_parses`), never a silent empty catalog
/// (ADR 0026).
pub fn bundled_catalog() -> &'static Catalog {
    static BUNDLED: OnceLock<Catalog> = OnceLock::new();
    BUNDLED.get_or_init(|| {
        Catalog::parse(CATALOG_SNAPSHOT).expect("the bundled models.dev snapshot is valid JSON")
    })
}

/// The catalog a route resolves its wire protocol from (ADR 0026): the
/// local cache when it parses, else the bundled snapshot. Never the network — a route is
/// resolved before the window fetch, and a missing catalog is not an error.
pub fn protocol_catalog() -> Catalog {
    read_cache(&cache_path())
        .map(|(catalog, _)| catalog)
        .unwrap_or_else(|| bundled_catalog().clone())
}

/// The hostname→provider map for deriving the catalog provider from `--base-url`. Matched by
/// hostname only (ADR 0018): a provider's `api` field and the owner's base URL differ in path.
pub fn provider_for_host(host: &str) -> Option<&'static str> {
    match host.trim_end_matches('.').to_ascii_lowercase().as_str() {
        "opencode.ai" => Some("opencode"),
        "api.anthropic.com" => Some("anthropic"),
        "api.openai.com" => Some("openai"),
        "api.deepseek.com" => Some("deepseek"),
        // Verified against the 2026-10-13 catalog (their `api` hostnames).
        "openrouter.ai" => Some("openrouter"),
        "api.moonshot.cn" => Some("moonshotai-cn"),
        _ => None,
    }
}

/// The hostname of a base URL, lower-cased, without userinfo or port. `None` when the URL has
/// no authority or does not parse.
pub fn host_of(base_url: &str) -> Option<String> {
    let rest = base_url.split_once("://")?.1;
    let authority = rest.split(['/', '?', '#']).next()?;
    let authority = authority
        .rsplit_once('@')
        .map_or(authority, |(_, host)| host);
    let host = if authority.starts_with('[') {
        authority.split(']').next()?.trim_start_matches('[')
    } else {
        authority.split(':').next()?
    };
    (!host.is_empty()).then(|| host.to_ascii_lowercase())
}

/// One model's limits as the catalog reports them. The three numbers are kept **separately**
/// (ADR 0018): `context` is the total window `C`, `input` the input ceiling `I`
/// when the provider publishes one, and `output` the output ceiling. A missing or zero value
/// means "unknown", never a fabricated number.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ModelLimit {
    pub context: Option<u64>,
    pub output: Option<u64>,
    pub input: Option<u64>,
}

impl ModelLimit {
    /// All three numbers unknown — the value a descriptor that draws its numbers from the
    /// catalog carries, and what `Default` means here. A `const` (rather than only the derived
    /// `Default`) because the descriptor table's builders are `const fn`.
    pub const UNKNOWN: Self = Self {
        context: None,
        output: None,
        input: None,
    };
}

impl Default for ModelLimit {
    fn default() -> Self {
        Self::UNKNOWN
    }
}

/// One model's unit prices from the catalog (ADR 0027), in **millionths of a US
/// dollar per million tokens**. models.dev reports `cost.{input,output,cache_read,cache_write}`
/// as dollars per million tokens (e.g. `input: 3` is $3/Mtok); a float would break `Eq`, so the
/// parsed values are kept as integers rounded to a micro-dollar, enough for every price in the
/// 2026-10-14 catalog. A missing field is "unknown", never 0.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ModelPrice {
    /// Micro-dollars per million input tokens (`3` → `3_000_000`).
    pub input: u64,
    pub output: u64,
    pub cache_read: Option<u64>,
    pub cache_write: Option<u64>,
    /// Context tiers (models.dev `cost.tiers`), ascending by `size`. Empty when the model has
    /// none: the base rates above apply to every request then.
    pub tiers: Vec<PriceTier>,
}

/// One context tier (models.dev `cost.tiers`, research F5): the rates that apply to a request
/// whose prompt is **over** `size` tokens. The tier carries a full rate set (the same shape as
/// the base), not an incremental rate: it replaces the base rates for the whole request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PriceTier {
    /// The context threshold in tokens (`tier.size`).
    pub size: u64,
    pub input: u64,
    pub output: u64,
    pub cache_read: Option<u64>,
    pub cache_write: Option<u64>,
}

/// The rates one request is billed at, base or tier.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PriceRates {
    pub input: u64,
    pub output: u64,
    pub cache_read: Option<u64>,
    pub cache_write: Option<u64>,
}

impl ModelPrice {
    /// Whether the price can produce a cost at all: both the input and output rates are known.
    pub fn is_usable(&self) -> bool {
        self.input > 0 || self.output > 0
    }

    /// The rates for a request whose prompt is `prompt` tokens: the highest tier the prompt
    /// **exceeds** (`prompt > size`), else the base rates. A `None` prompt (the provider
    /// reported no input counter) uses the base rates.
    pub fn rates_for(&self, prompt: Option<u64>) -> PriceRates {
        let tier =
            prompt.and_then(|prompt| self.tiers.iter().rev().find(|tier| prompt > tier.size));
        match tier {
            Some(tier) => PriceRates {
                input: tier.input,
                output: tier.output,
                cache_read: tier.cache_read,
                cache_write: tier.cache_write,
            },
            None => PriceRates {
                input: self.input,
                output: self.output,
                cache_read: self.cache_read,
                cache_write: self.cache_write,
            },
        }
    }
}

/// Parses a models.dev `cost` object (`dollars per million tokens`) into micro-dollars,
/// including its context tiers.
fn parse_price(cost: &serde_json::Map<String, Value>) -> Option<ModelPrice> {
    let rate = |object: &serde_json::Map<String, Value>, key: &str| {
        object
            .get(key)
            .and_then(Value::as_f64)
            .filter(|value| *value >= 0.0)
            .map(|value| (value * 1_000_000.0).round() as u64)
    };
    let mut price = ModelPrice {
        input: rate(cost, "input")?,
        output: rate(cost, "output")?,
        cache_read: rate(cost, "cache_read"),
        cache_write: rate(cost, "cache_write"),
        tiers: Vec::new(),
    };
    if !price.is_usable() {
        return None;
    }
    price.tiers = parse_tiers(cost);
    Some(price)
}

/// The context tiers. `tiers` is the current spelling; `context_over_200k` is the legacy one
/// (the same rates at a fixed 200_000, models.dev `schema.ts`). A tier without its own
/// input/output is skipped: the base rates stand for it.
fn parse_tiers(cost: &serde_json::Map<String, Value>) -> Vec<PriceTier> {
    let tier_of = |object: &serde_json::Map<String, Value>, size: u64| -> Option<PriceTier> {
        let rate = |key: &str| {
            object
                .get(key)
                .and_then(Value::as_f64)
                .filter(|value| *value >= 0.0)
                .map(|value| (value * 1_000_000.0).round() as u64)
        };
        Some(PriceTier {
            size,
            input: rate("input")?,
            output: rate("output")?,
            cache_read: rate("cache_read"),
            cache_write: rate("cache_write"),
        })
    };
    let mut tiers = Vec::new();
    if let Some(list) = cost.get("tiers").and_then(Value::as_array) {
        for entry in list {
            let Some(object) = entry.as_object() else {
                continue;
            };
            let Some(size) = object
                .get("tier")
                .and_then(|tier| tier.get("size"))
                .and_then(Value::as_u64)
            else {
                continue;
            };
            if let Some(tier) = tier_of(object, size) {
                tiers.push(tier);
            }
        }
    } else if let Some(legacy) = cost.get("context_over_200k").and_then(Value::as_object)
        && let Some(tier) = tier_of(legacy, 200_000)
    {
        tiers.push(tier);
    }
    // Ascending, so `rates_for` can take the last one the prompt exceeds.
    tiers.sort_by_key(|tier| tier.size);
    tiers
}

/// The plain-text `interleaved` field names Radian knows how to replay (ADR 0014
/// Q2). `reasoning_details` is a structured array with a different shape, so it is deliberately
/// not replayed: that is unsupported, not supported. A bare `true` names no field at all and is
/// likewise not replayed.
const REPLAYABLE_INTERLEAVED: [&str; 3] = ["reasoning_content", "reasoning", "reasoning_text"];

/// The `interleaved` catalog value as a replay field name: `{"field": "reasoning_content"}`
/// and the other plain-text names are replayed; `reasoning_details`, a bare `true`, and a
/// missing entry are not (ADR 0014 Q2).
fn parse_interleaved(value: &Value) -> Option<String> {
    let field = value.get("field").and_then(Value::as_str)?;
    REPLAYABLE_INTERLEAVED
        .contains(&field)
        .then(|| field.to_owned())
}

/// The **cap** on the output reservation `R` (ADR 0018): the reservation is a
/// quarter of the window, never more than this. A fixed 16384 made any window at or below 16K
/// have no budget at all.
pub const OUTPUT_RESERVATION_CAP: u64 = 16_384;

/// `R = max(min(16384, ⌊C/4⌋), request_max_output)` (ADR 0018).
///
/// The reservation scales with the window — a quarter, capped at [`OUTPUT_RESERVATION_CAP`] —
/// so a small-window model still has a budget. The request's **actual** output setting raises
/// it further, because that output really does occupy the window; a provider that sends no
/// such field does not raise it. `C` unknown: `R` does not take part in `B`, and the value is
/// the request's own output (0 when there is none). The catalog's `limit.output` is a
/// capability ceiling and does **not** participate.
pub fn output_reservation(context: Option<u64>, request_max_output: Option<u32>) -> u64 {
    let request = u64::from(request_max_output.unwrap_or(0));
    match context.filter(|tokens| *tokens > 0) {
        Some(context) => OUTPUT_RESERVATION_CAP.min(context / 4).max(request),
        None => request,
    }
}

/// ADR 0018's effective input budget `B = min(I, C − R)`.
///
/// `context` is `C` (`--context-window` when given, else the catalog), `input` is `I` (catalog
/// only), and `request_max_output` is the output the request itself sets. A missing or zero
/// value is unknown, never a fabricated number. `C ≤ R` is an error: the window cannot hold
/// the reservation.
pub fn input_budget(
    context: Option<u64>,
    input: Option<u64>,
    request_max_output: Option<u32>,
) -> Result<Option<u64>, String> {
    let context = context.filter(|tokens| *tokens > 0);
    let input = input.filter(|tokens| *tokens > 0);
    match (context, input) {
        (Some(context), input) => {
            let reservation = output_reservation(Some(context), request_max_output);
            if context <= reservation {
                return Err(format!(
                    "the context window ({context} tokens) is not larger than the output \
                     reservation ({reservation} tokens: a quarter of the window, capped at \
                     {OUTPUT_RESERVATION_CAP}, raised by the request's max output); raise \
                     --context-window or lower the request's max output"
                ));
            }
            let after_reservation = context - reservation;
            Ok(Some(input.map_or(after_reservation, |input| {
                input.min(after_reservation)
            })))
        }
        (None, Some(input)) => Ok(Some(input)),
        (None, None) => Ok(None),
    }
}

/// Checks the **flag** `--context-window` (ADR 0015).
///
/// An explicit `0` is a usage error: the user typed a window that cannot hold any output
/// reservation, and silently reading it as "not given" would hide the mistake. That is the
/// flag's rule only — the config's `[model] context_window = 0` is the config's spelling of
/// "unset", and the reader maps it to `None` before either host sees it. Both hosts call this,
/// so `radian exec` and the TUI refuse the same command line the same way, before a session
/// file exists.
pub fn check_context_window_flag(flag: Option<u64>) -> Result<(), String> {
    if flag == Some(0) {
        return Err("--context-window must be at least 1 token".to_string());
    }
    Ok(())
}

/// A one-line warning when the request's output setting is above the catalog's output ceiling
/// (ADR 0018: the ceiling is checked, not used in `R`).
pub fn output_ceiling_warning(
    request_max_output: Option<u32>,
    output_ceiling: Option<u64>,
) -> Option<String> {
    let request = u64::from(request_max_output?);
    let ceiling = output_ceiling.filter(|value| *value > 0)?;
    (request > ceiling).then(|| {
        format!(
            "[budget] warning: the request's max output ({request}) is above the catalog's \
             output ceiling for this model ({ceiling})"
        )
    })
}

/// One provider's catalog metadata (ADR 0026 D0). `env`/`name` are read so a descriptor can
/// fall back to the catalog; only models that carry a `limit` are kept, so the existing window
/// behavior is unchanged. There is deliberately **no** `api` here: radian never trusts the
/// catalog's base URL (ADR 0026).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProviderInfo {
    pub id: String,
    /// The provider's display name (`"OpenCode Go"`).
    pub name: Option<String>,
    /// The environment variables the provider reads its key from. Informational only: ADR 0026
    /// D2 makes `auth.json` the only runtime source.
    pub env: Vec<String>,
}

/// One model in the catalog, for `/model`'s list (ADR 0026 D0). `limit` is the window ADR 0018
/// uses; a model without a `limit` is not in the catalog at all (existing behavior).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ModelEntry {
    pub id: String,
    /// The model's display name (`"Claude Opus 5.5"`), when the catalog has one.
    pub name: Option<String>,
    pub limit: ModelLimit,
}

/// One catalog model as parsed.
#[derive(Debug, Clone, PartialEq, Eq)]
struct CatalogModel {
    name: Option<String>,
    limit: ModelLimit,
    price: Option<ModelPrice>,
    /// The `interleaved` field the model requires its reasoning replayed under, when the
    /// catalog names a plain-text field (ADR 0014 Q2). `None` for a missing entry,
    /// a bare `true`, or a structured field Radian does not replay (`reasoning_details`).
    reasoning_replay: Option<String>,
    /// The model entry's own `provider.npm` (ADR 0026), when it carries
    /// one; the provider-level `npm` in [`CatalogProvider`] is the fallback.
    npm: Option<String>,
}

/// One catalog provider as parsed.
#[derive(Debug, Clone, PartialEq, Eq)]
struct CatalogProvider {
    name: Option<String>,
    env: Vec<String>,
    /// The provider-level `npm` (ADR 0026): the wire protocol every model
    /// of this provider uses unless its entry names its own.
    npm: Option<String>,
    models: BTreeMap<String, CatalogModel>,
}

/// The parsed catalog: provider id → provider metadata and its models.
#[derive(Debug, Clone, Default)]
pub struct Catalog {
    providers: BTreeMap<String, CatalogProvider>,
}

impl Catalog {
    /// Parses `api.json`. Unknown fields and missing `limit` fields are ignored; a top-level
    /// that is not an object is "corrupt" and returns `None` (treated as no cache).
    pub fn parse(text: &str) -> Option<Self> {
        let root: Value = serde_json::from_str(text).ok()?;
        let Value::Object(providers) = root else {
            return None;
        };
        let mut parsed = BTreeMap::new();
        for (provider_id, provider) in providers {
            let Some(models) = provider.get("models").and_then(Value::as_object) else {
                continue;
            };
            let mut models_out = BTreeMap::new();
            for (model_id, model) in models {
                let Some(limit) = model.get("limit").and_then(Value::as_object) else {
                    continue;
                };
                models_out.insert(
                    model_id.clone(),
                    CatalogModel {
                        name: model.get("name").and_then(Value::as_str).map(str::to_owned),
                        price: model
                            .get("cost")
                            .and_then(Value::as_object)
                            .and_then(parse_price),
                        reasoning_replay: model.get("interleaved").and_then(parse_interleaved),
                        npm: model
                            .get("provider")
                            .and_then(|provider| provider.get("npm"))
                            .and_then(Value::as_str)
                            .map(str::to_owned),
                        limit: ModelLimit {
                            context: limit.get("context").and_then(Value::as_u64),
                            output: limit.get("output").and_then(Value::as_u64),
                            input: limit.get("input").and_then(Value::as_u64),
                        },
                    },
                );
            }
            if !models_out.is_empty() {
                parsed.insert(
                    provider_id.clone(),
                    CatalogProvider {
                        name: provider
                            .get("name")
                            .and_then(Value::as_str)
                            .map(str::to_owned),
                        npm: provider.get("npm").and_then(Value::as_str).map(str::to_owned),
                        env: provider
                            .get("env")
                            .and_then(Value::as_array)
                            .map(|values| {
                                values
                                    .iter()
                                    .filter_map(Value::as_str)
                                    .map(str::to_owned)
                                    .collect()
                            })
                            .unwrap_or_default(),
                        models: models_out,
                    },
                );
            }
        }
        Some(Self { providers: parsed })
    }

    pub fn limit(&self, provider: &str, model: &str) -> Option<ModelLimit> {
        self.providers
            .get(provider)?
            .models
            .get(model)
            .map(|entry| entry.limit)
    }

    /// The model's unit prices (ADR 0027), or `None` when the catalog has none.
    pub fn price(&self, provider: &str, model: &str) -> Option<ModelPrice> {
        self.providers
            .get(provider)?
            .models
            .get(model)
            .and_then(|entry| entry.price.clone())
    }

    /// The reasoning-replay field the catalog declares for a model (ADR 0014 Q2),
    /// or `None` when the entry is missing or names a field Radian does not replay.
    pub fn reasoning_replay(&self, provider: &str, model: &str) -> Option<String> {
        self.providers
            .get(provider)?
            .models
            .get(model)?
            .reasoning_replay
            .clone()
    }

    /// The `npm` that decides a built-in descriptor's wire protocol for `(provider, model)`
    /// (ADR 0026): the entry's own `provider.npm`, else the provider-level
    /// `npm`. `None` when the catalog has no entry for the model at all — the built-in table
    /// decides then.
    pub fn npm(&self, provider: &str, model: &str) -> Option<&str> {
        let provider_entry = self.providers.get(provider)?;
        let model_entry = provider_entry.models.get(model)?;
        model_entry
            .npm
            .as_deref()
            .or(provider_entry.npm.as_deref())
    }

    /// The provider's catalog metadata (display name, `env`), if present.
    pub fn provider_info(&self, provider: &str) -> Option<ProviderInfo> {
        let entry = self.providers.get(provider)?;
        Some(ProviderInfo {
            id: provider.to_owned(),
            name: entry.name.clone(),
            env: entry.env.clone(),
        })
    }

    /// The provider's models, in id order, for `/model`'s list.
    pub fn models_for(&self, provider: &str) -> Vec<ModelEntry> {
        self.providers
            .get(provider)
            .map(|entry| {
                entry
                    .models
                    .iter()
                    .map(|(id, model)| ModelEntry {
                        id: id.clone(),
                        name: model.name.clone(),
                        limit: model.limit,
                    })
                    .collect()
            })
            .unwrap_or_default()
    }

    /// The model's display name (`"Claude Opus 5.5"`), or `None` when the catalog has no such
    /// model or no name for it.
    pub fn display_name(&self, provider: &str, model: &str) -> Option<&str> {
        self.providers
            .get(provider)?
            .models
            .get(model)?
            .name
            .as_deref()
    }

    pub fn provider_count(&self) -> usize {
        self.providers.len()
    }

    pub fn model_count(&self, provider: &str) -> usize {
        self.providers
            .get(provider)
            .map_or(0, |entry| entry.models.len())
    }
}

/// Where a resolved window came from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WindowSource {
    /// An explicit `--context-window`.
    Explicit,
    /// The catalog, with the matched provider/model and how old the data is.
    Catalog {
        provider: String,
        model: String,
        age: Option<Duration>,
    },
    /// The **bundled** models.dev snapshot (ADR 0026): the last fallback
    /// when there is no cache and the fetch failed. `date` is [`SNAPSHOT_DATE`].
    Bundled {
        provider: String,
        model: String,
        date: &'static str,
    },
    /// The route's own descriptor table ([`crate::DescriptorModel::limit`]): the numbers the
    /// `chatgpt` descriptor cites from `@oh-my-pi/pi-catalog`'s `openai-codex` block, for a
    /// provider models.dev does not carry.
    Descriptor { provider: String, model: String },
    /// Nothing matched; the budget is off.
    Unknown,
}

/// The resolved window for a run: the numbers ADR 0018 distinguishes, plus the effective input
/// budget `B` computed from them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Window {
    /// The effective input budget `B`, or `None` when it cannot be computed (window unknown).
    pub budget: Option<u64>,
    /// `Some` when the window cannot hold the output reservation. See [`Window::startup_check`]
    /// for what a host does with it.
    pub error: Option<String>,
    /// `C`: `--context-window` when given, else the catalog's `limit.context`.
    pub context: Option<u64>,
    /// `I`: the catalog's `limit.input` (never from `--context-window`).
    pub input: Option<u64>,
    /// The catalog's output ceiling (a capability; only used for a warning).
    pub output: Option<u64>,
    /// `R`: the output reservation used to compute `B`.
    pub reservation: u64,
    pub source: WindowSource,
    pub limit: Option<ModelLimit>,
    /// The model's unit prices (ADR 0027), when the catalog has them: the footer's
    /// `cost` item. `None` means the cost is not shown (never a fabricated number).
    pub price: Option<ModelPrice>,
}

/// What a host does at startup with a [`Window`] whose `C ≤ R`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WindowCheck {
    /// Nothing to report.
    Ok,
    /// The user's own `--context-window` cannot hold the reservation: refuse to start.
    Refuse(String),
    /// The catalog's window cannot hold the reservation (a small model): warn, and run with
    /// the budget off. Refusing would make a small-window model unusable for a number the user
    /// never typed; the provider's own overflow error still ends a turn (ADR 0017).
    Warn(String),
}

impl Window {
    /// The startup decision for `C ≤ R`: refuse for an explicit `--context-window`, warn for
    /// a catalog window (the budget is already `None` then).
    pub fn startup_check(&self) -> WindowCheck {
        match (&self.error, &self.source) {
            (None, _) => WindowCheck::Ok,
            (Some(error), WindowSource::Explicit) => {
                WindowCheck::Refuse(format!("--context-window: {error}"))
            }
            (Some(error), _) => WindowCheck::Warn(format!(
                "[budget] warning: the catalog's window for this model {error}; the context \
                 budget is off"
            )),
        }
    }

    fn unknown() -> Self {
        Self {
            budget: None,
            error: None,
            context: None,
            input: None,
            output: None,
            // `C` is unknown, so `R` does not enter `B`; `describe` shows it as `?`.
            reservation: 0,
            source: WindowSource::Unknown,
            limit: None,
            price: None,
        }
    }

    /// The one startup line (ADR 0018): the numbers, the effective budget `B`, and exactly
    /// where they came from. It never contains a key, a header value or a URL.
    pub fn describe(&self) -> String {
        let numbers = format!(
            "C {}, I {}, output {}, R {}, B {}",
            number(self.context),
            number(self.input),
            number(self.output),
            number(Some(self.reservation)),
            number(self.budget),
        );
        let origin = match &self.source {
            WindowSource::Explicit => "from --context-window".to_string(),
            WindowSource::Catalog {
                provider,
                model,
                age,
            } => format!(
                "from models.dev ({provider}/{model}, {})",
                match age {
                    Some(age) if *age < Duration::from_secs(60) => "just fetched".to_string(),
                    Some(age) => format!("cached {} ago", human_age(*age)),
                    None => "age unknown".to_string(),
                }
            ),
            WindowSource::Descriptor { provider, model } => {
                format!("from the {provider} descriptor ({provider}/{model})")
            }
            WindowSource::Bundled {
                provider,
                model,
                date,
            } => format!("from bundled snapshot ({date}) ({provider}/{model})"),
            WindowSource::Unknown => "unknown".to_string(),
        };
        match (&self.error, self.budget) {
            (Some(error), _) => format!("no input budget: {error}"),
            (None, Some(_)) => format!("{numbers} {origin}"),
            (None, None) => format!(
                "window unknown ({numbers}); no budget, only the provider's over-length error \
                 remains"
            ),
        }
    }
}

fn number(value: Option<u64>) -> String {
    value
        .filter(|value| *value > 0)
        .map_or_else(|| "?".to_string(), |value| value.to_string())
}

fn human_age(age: Duration) -> String {
    let secs = age.as_secs();
    if secs < 60 {
        format!("{secs} s")
    } else if secs < 60 * 60 {
        format!("{} min", secs / 60)
    } else {
        format!("{} h", secs / (60 * 60))
    }
}

/// Everything the resolver needs. `cache_path`/`url` are explicit so tests never touch the
/// real cache or the network; [`WindowQuery::production`] fills them from the environment.
#[derive(Debug, Clone)]
pub struct WindowQuery {
    /// The explicit window (`--context-window` / `[model] context_window`). ADR 0015: a `0`
    /// means unset — not an explicit window at all — so the catalog decides, exactly as if the
    /// value had not been given ([`WindowQuery::production`] drops it). A host never sends the
    /// flag's `0` here: [`check_context_window_flag`] refuses it first.
    pub explicit: Option<u64>,
    pub catalog_provider: Option<String>,
    pub base_url: String,
    pub model: String,
    /// The output the request itself sets (`max_tokens`), for `R`; `None` for providers that
    /// do not send one.
    pub request_max_output: Option<u32>,
    pub offline: bool,
    pub cache_path: PathBuf,
    pub url: String,
}

impl WindowQuery {
    /// The production query: the real cache path and [`CATALOG_URL`] (or the
    /// `RADIAN_CATALOG_URL` test seam when set).
    pub fn production(
        explicit: Option<u64>,
        catalog_provider: Option<String>,
        base_url: impl Into<String>,
        model: impl Into<String>,
        request_max_output: Option<u32>,
        offline: bool,
    ) -> Self {
        Self {
            // ADR 0015: a zero window is unset, never an explicit window. A host cannot reach
            // here with one — `check_context_window_flag` refuses the flag's zero and the config
            // reader maps the key's zero to `None` — so this is the last guard, not the rule:
            // were a zero to arrive, the catalog decides (B never becomes a zero-token budget).
            explicit: explicit.filter(|tokens| *tokens > 0),
            catalog_provider,
            base_url: base_url.into(),
            model: model.into(),
            request_max_output,
            offline,
            cache_path: cache_path(),
            url: std::env::var("RADIAN_CATALOG_URL").unwrap_or_else(|_| CATALOG_URL.to_string()),
        }
    }

    fn provider(&self) -> Option<String> {
        self.catalog_provider.clone().or_else(|| {
            host_of(&self.base_url).and_then(|host| provider_for_host(&host).map(str::to_owned))
        })
    }
}

/// The catalog cache file: `~/.radian/cache/catalog/models.json` (ADR 0020's layout).
pub fn cache_path() -> PathBuf {
    match crate::home::catalog_cache() {
        Some(path) => path,
        // No HOME: a path the write will fail on, so the window stays unknown.
        None => PathBuf::from("radian-catalog-models.json"),
    }
}

/// Where a loaded catalog came from.
enum LoadSource {
    /// The local cache, with its age (which may be [`Duration::ZERO`] for a just-fetched one).
    Cache(Duration),
    /// The bundled snapshot (ADR 0026).
    Bundled,
}

impl LoadSource {
    /// The [`WindowSource`] a window found in this catalog is reported as.
    fn window_source(&self, provider: &str, model: &str) -> WindowSource {
        match self {
            Self::Cache(age) => WindowSource::Catalog {
                provider: provider.to_owned(),
                model: model.to_owned(),
                age: Some(*age),
            },
            Self::Bundled => WindowSource::Bundled {
                provider: provider.to_owned(),
                model: model.to_owned(),
                date: SNAPSHOT_DATE,
            },
        }
    }
}

/// Resolves the window: `--context-window`, then the catalog (cache, fetch, stale cache, the
/// bundled snapshot), then the route's own descriptor table, then unknown.
pub async fn resolve(query: &WindowQuery) -> Window {
    if let Some(explicit) = query.explicit {
        // ADR 0018: an explicit window never fetches. If a cache already exists,
        // its `input`/`output` are read from it; otherwise only the explicit number is used.
        let cached = query.provider().and_then(|provider| {
            read_cache(&query.cache_path).map(|(catalog, _)| {
                (
                    catalog.limit(&provider, &query.model),
                    catalog.price(&provider, &query.model),
                )
            })
        });
        let (limit, price) = cached.unwrap_or((None, None));
        let input = limit.and_then(|limit| limit.input);
        let output = limit.and_then(|limit| limit.output);
        return build_window(
            Some(explicit),
            input,
            output,
            query.request_max_output,
            WindowSource::Explicit,
            limit,
            price,
        );
    }
    let Some(provider) = query.provider() else {
        return Window::unknown();
    };
    let (catalog, source) = load(&query.cache_path, &query.url, query.offline).await;
    if let Some(catalog) = catalog.as_ref()
        && let Some(limit) = catalog.limit(&provider, &query.model)
    {
        let price = catalog.price(&provider, &query.model);
        let source = source
            .as_ref()
            .map_or(WindowSource::Unknown, |s| s.window_source(&provider, &query.model));
        return build_window(
            limit.context,
            limit.input,
            limit.output,
            query.request_max_output,
            source,
            Some(limit),
            price,
        );
    }
    descriptor_window(query, &provider).unwrap_or_else(Window::unknown)
}

/// Resolves a window **offline**: the local catalog cache, else the bundled snapshot, never the
/// network. This is what the driver's budget resolver uses (ADR 0026 D7): a `/model` switch
/// recomputes `B` from the warm cache (or the snapshot), and a miss means "unknown", not a
/// fetch — unless the route's own descriptor table carries the numbers (a `chatgpt` switch has
/// no cache entry to miss).
pub fn resolve_offline(query: &WindowQuery) -> Window {
    let Some(provider) = query.provider() else {
        return Window::unknown();
    };
    let loaded = read_cache(&query.cache_path)
        .map(|(catalog, age)| (catalog, LoadSource::Cache(age)))
        .unwrap_or_else(|| (bundled_catalog().clone(), LoadSource::Bundled));
    if let Some(limit) = loaded.0.limit(&provider, &query.model) {
        let price = loaded.0.price(&provider, &query.model);
        return build_window(
            limit.context,
            limit.input,
            limit.output,
            query.request_max_output,
            loaded.1.window_source(&provider, &query.model),
            Some(limit),
            price,
        );
    }
    descriptor_window(query, &provider).unwrap_or_else(Window::unknown)
}

/// The window from the route's own descriptor table ([`crate::DescriptorModel::limit`]): the
/// fallback for a provider models.dev does not carry, such as `chatgpt`. `None` when the
/// provider is not a built-in descriptor or its table carries no numbers for this model — the
/// window stays unknown rather than guessed.
fn descriptor_window(query: &WindowQuery, provider: &str) -> Option<Window> {
    let limit = crate::descriptor(provider)?.limit_for(&query.model)?;
    Some(build_window(
        limit.context,
        limit.input,
        limit.output,
        query.request_max_output,
        WindowSource::Descriptor {
            provider: provider.to_owned(),
            model: query.model.clone(),
        },
        Some(limit),
        // No price: models.dev is the price source (ADR 0027), and it has no
        // `chatgpt` provider either.
        None,
    ))
}

/// Computes `B` and assembles a [`Window`], keeping a `C ≤ R` error instead of failing here
/// (the host decides how to report it).
fn build_window(
    context: Option<u64>,
    input: Option<u64>,
    output: Option<u64>,
    request_max_output: Option<u32>,
    source: WindowSource,
    limit: Option<ModelLimit>,
    price: Option<ModelPrice>,
) -> Window {
    let reservation = output_reservation(context, request_max_output);
    match input_budget(context, input, request_max_output) {
        Ok(budget) => Window {
            budget,
            error: None,
            context,
            input,
            output,
            reservation,
            source,
            limit,
            price,
        },
        Err(error) => Window {
            budget: None,
            error: Some(error),
            context,
            input,
            output,
            reservation,
            source,
            limit,
            price,
        },
    }
}

/// Loads the catalog from the cache, the network, or the bundled snapshot (ADR 0026
/// decision 3). Returns the catalog and where it came from. Never fails: a fetch failure falls
/// back to a stale cache, then to the snapshot, and offline uses the cache, then the snapshot.
async fn load(
    cache_path: &Path,
    url: &str,
    offline: bool,
) -> (Option<Catalog>, Option<LoadSource>) {
    let cached = read_cache(cache_path);
    if offline {
        return match cached {
            Some((catalog, age)) => (Some(catalog), Some(LoadSource::Cache(age))),
            None => (Some(bundled_catalog().clone()), Some(LoadSource::Bundled)),
        };
    }
    if let Some((catalog, age)) = &cached
        && *age < CACHE_TTL
    {
        return (Some(catalog.clone()), Some(LoadSource::Cache(*age)));
    }
    match fetch(url).await.and_then(|text| {
        let catalog = Catalog::parse(&text)?;
        Some((catalog, text))
    }) {
        Some((catalog, text)) => {
            let _ = write_cache(cache_path, &text);
            (Some(catalog), Some(LoadSource::Cache(Duration::ZERO)))
        }
        None => match cached {
            Some((catalog, age)) => (Some(catalog), Some(LoadSource::Cache(age))),
            None => (Some(bundled_catalog().clone()), Some(LoadSource::Bundled)),
        },
    }
}

/// Reads and parses the cache. A missing file, an unreadable one, or corrupt JSON is "no
/// cache". The age comes from the file's mtime.
fn read_cache(path: &Path) -> Option<(Catalog, Duration)> {
    let text = std::fs::read_to_string(path).ok()?;
    let catalog = Catalog::parse(&text)?;
    let modified = std::fs::metadata(path).ok()?.modified().ok()?;
    let age = SystemTime::now()
        .duration_since(modified)
        .unwrap_or(Duration::ZERO);
    Some((catalog, age))
}

/// The catalog's reasoning-replay field for `(provider, model)`, read from the local cache
/// (ADR 0014 Q2). `None` when the cache is missing, the entry is absent, or the
/// entry declares a field Radian does not replay. Offline, like the budget resolver: a switch
/// never fetches.
pub fn catalog_reasoning_replay(provider: &str, model: &str) -> Option<String> {
    let (catalog, _) = read_cache(&cache_path())?;
    catalog.reasoning_replay(provider, model)
}

/// Writes the cache atomically (temp file + rename) with owner-only permissions.
fn write_cache(path: &Path, text: &str) -> io::Result<()> {
    let dir = path.parent().ok_or_else(|| {
        io::Error::new(io::ErrorKind::InvalidInput, "cache path has no directory")
    })?;
    radian_session::ensure_private_dir(dir)?;
    let tmp = path.with_extension(format!("tmp-{}", std::process::id()));
    {
        let mut options = std::fs::OpenOptions::new();
        options.write(true).create(true).truncate(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(radian_session::PRIVATE_FILE_MODE);
        }
        let mut file = options.open(&tmp)?;
        file.write_all(text.as_bytes())?;
        file.sync_all()?;
    }
    std::fs::rename(&tmp, path)
}

/// One read-only GET with a short timeout, no key and no custom headers.
async fn fetch(url: &str) -> Option<String> {
    let client = reqwest::Client::builder()
        .timeout(FETCH_TIMEOUT)
        .build()
        .ok()?;
    let response = client.get(url).send().await.ok()?;
    if !response.status().is_success() {
        return None;
    }
    response.text().await.ok()
}

